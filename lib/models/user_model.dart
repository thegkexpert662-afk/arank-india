class UserModel {
  final String uid;
  final String name;
  final String email;
  final String mobile;
  final String photoUrl;
  final String state;
  final String city;

  UserModel({
    required this.uid,
    required this.name,
    required this.email,
    required this.mobile,
    required this.photoUrl,
    required this.state,
    required this.city,
  });
}